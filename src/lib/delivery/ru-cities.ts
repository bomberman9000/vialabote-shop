const norm = (s: string) => s.trim().toLowerCase().replace(/ё/g, "е").replace(/[\s-]+/g, " ");

/** Город по введённому названию: без учёта регистра, «ё», дефисов и лишних пробелов; «г. Самара» тоже. */
export function findCity(input: string): RuCity | null {
  const q = norm(input.replace(/^\s*г\.?\s+/i, ""));
  if (!q) return null;
  return RU_CITIES.find((c) => norm(c.name) === q) ?? null;
}
